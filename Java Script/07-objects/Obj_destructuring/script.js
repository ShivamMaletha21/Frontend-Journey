// array destrcuting
let arr = ["Shivam", 20, "India"];

let [name, age, country] = arr;

console.log(name);    // Shivam
console.log(age);     // 20
console.log(country); // India



// object destructuing
let person = {
    name: "Shivam",
    age: 20,
    city: "Dehradun"
};

let { name, age, city } = person;

console.log(name); // Shivam
console.log(age);  // 20
console.log(city); // Dehradun